--comment: Per-stadium time-based pricing rules (day_of_week: 0=Monday .. 6=Sunday)
CREATE TABLE pricing_rules (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stadium_id     BIGINT NOT NULL REFERENCES stadiums (id) ON DELETE CASCADE,
    day_of_week    INTEGER NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
    start_time     TIME NOT NULL,
    end_time       TIME NOT NULL,
    price_per_hour INTEGER NOT NULL CHECK (price_per_hour >= 0),
    is_active      BOOLEAN NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_pricing_rule_slot UNIQUE (stadium_id, day_of_week, start_time, end_time),
    CONSTRAINT chk_pricing_rule_time_order CHECK (start_time < end_time)
);

CREATE INDEX idx_pricing_rules_stadium_id ON pricing_rules (stadium_id);
