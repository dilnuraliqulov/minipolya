--comment: Payments and refunds. provider_txn_id UNIQUE makes webhook processing idempotent; refunds are NEW rows with negative amounts (original rows are never mutated).
CREATE TABLE payments (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id           BIGINT REFERENCES bookings (id),
    game_id              BIGINT REFERENCES games (id),
    user_id              BIGINT NOT NULL REFERENCES users (id),
    amount               INTEGER NOT NULL,
    payment_type         VARCHAR(20) NOT NULL CHECK (payment_type IN ('booking', 'game_share', 'service_fee', 'refund')),
    provider             VARCHAR(20) NOT NULL CHECK (provider IN ('payme', 'click', 'cash')),
    provider_txn_id      VARCHAR(255) UNIQUE,
    status               VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'completed', 'failed', 'refunded')),
    refund_reason        VARCHAR(255),
    refund_of_payment_id BIGINT REFERENCES payments (id),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_payments_user_id ON payments (user_id);
CREATE INDEX idx_payments_booking_id ON payments (booking_id);
CREATE INDEX idx_payments_game_id ON payments (game_id);
CREATE INDEX idx_payments_status ON payments (status);
