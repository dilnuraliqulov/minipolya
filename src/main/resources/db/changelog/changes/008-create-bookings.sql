--comment: Bookings table with a DB-level EXCLUDE constraint that makes double-booking impossible
CREATE TABLE bookings (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stadium_id          BIGINT NOT NULL REFERENCES stadiums (id) ON DELETE CASCADE,
    user_id             BIGINT REFERENCES users (id),
    game_id             BIGINT,
    booking_series_id   BIGINT REFERENCES booking_series (id),
    source              VARCHAR(20) NOT NULL DEFAULT 'app' CHECK (source IN ('app', 'manual', 'game')),
    status              VARCHAR(20) NOT NULL DEFAULT 'pending'
                            CHECK (status IN ('pending', 'confirmed', 'completed', 'expired',
                                              'cancelled_by_user', 'cancelled_by_owner')),
    starts_at           TIMESTAMPTZ NOT NULL,
    ends_at             TIMESTAMPTZ NOT NULL,
    duration_hours      INTEGER NOT NULL CHECK (duration_hours IN (1, 2)),
    price               INTEGER NOT NULL CHECK (price >= 0),
    client_name         VARCHAR(100),
    client_phone        VARCHAR(20),
    is_walkin           BOOLEAN NOT NULL DEFAULT FALSE,
    expires_at          TIMESTAMPTZ,
    cancelled_at        TIMESTAMPTZ,
    cancellation_reason TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_bookings_time_order CHECK (starts_at < ends_at),
    -- The safety net: the database itself rejects overlapping active bookings
    -- for the same stadium. Needs the btree_gist extension (changeset 001).
    CONSTRAINT bookings_no_overlap EXCLUDE USING gist (
        stadium_id WITH =,
        tstzrange(starts_at, ends_at) WITH &&
    ) WHERE (status IN ('pending', 'confirmed'))
);

CREATE INDEX idx_bookings_stadium_id ON bookings (stadium_id);
CREATE INDEX idx_bookings_user_id ON bookings (user_id);
CREATE INDEX idx_bookings_status ON bookings (status);
CREATE INDEX idx_bookings_starts_at ON bookings (starts_at);
CREATE INDEX idx_bookings_game_id ON bookings (game_id);

